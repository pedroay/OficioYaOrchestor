-- Modulo Identidad (diagrama entidad-relacion del equipo 1/ Argalle_Ayala_Caicedo_Rubiano).
-- Compatible con PostgreSQL y con H2 (modo PostgreSQL) usado en las pruebas.

-- Una credencial por usuario. user_id es una referencia logica al modulo User:
-- no hay llave foranea fisica porque esa tabla pertenece a otro modulo.
CREATE TABLE credential (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    failed_attempts     INTEGER      NOT NULL DEFAULT 0,
    locked_until        TIMESTAMP    NULL,
    last_login          TIMESTAMP    NULL,
    password_changed_at TIMESTAMP    NULL,
    CONSTRAINT uk_credential_user_id UNIQUE (user_id)
);

-- Un usuario (credencial) puede tener varios OTP (relacion 1 a 0..N).
-- Solo se guarda el hash del codigo, nunca el codigo en claro.
CREATE TABLE otp (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    code_hash  VARCHAR(255) NOT NULL,
    purpose    VARCHAR(30)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    used       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_otp_purpose CHECK (purpose IN ('RESET_PASSWORD')),
    CONSTRAINT fk_otp_credential_user FOREIGN KEY (user_id)
        REFERENCES credential (user_id) ON DELETE CASCADE
);

-- Indice sugerido en el ER para que findActive encuentre rapido el OTP vigente.
CREATE INDEX idx_otp_active ON otp (user_id, purpose, used, expires_at);
